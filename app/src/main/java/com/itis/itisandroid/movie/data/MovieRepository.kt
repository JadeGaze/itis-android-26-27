package com.itis.itisandroid.movie.data

import android.content.Context
import com.itis.itisandroid.data.local.AppDatabase
import com.itis.itisandroid.movie.data.local.MovieEntity
import com.itis.itisandroid.movie.presentation.model.Movie
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map

/**
 * Repository — the single source of truth for the movies data.
 *
 * Key concepts:
 * 1. **The Repository hides the data source.** The ViewModel does not know
 *    that we use Room/SQLite — it only calls repository methods and
 *    receives domain models ([Movie]) and reactive streams ([Flow]).
 *    Tomorrow we can replace the database with a network API
 *    without touching the ViewModel or the UI.
 *
 * 2. **Mapping**: the repository is the place where data-layer objects
 *    ([MovieEntity]) are converted into domain objects ([Movie])
 *    using map() on Flow (reactive conversion of every emission)
 *    and toDomain() / fromDomain() for single objects.
 *
 * 3. **suspend functions**: insert/update/delete are suspend functions
 *    because they perform blocking database operations on a background thread.
 */
class MovieRepository(context: Context) {

    // Grab the DAO from the singleton app database.
    // applicationContext is used so the database lives as long as the app process.
    private val dao = AppDatabase.getInstance(context).movieDao()

    /**
     * READ: returns all movies as a reactive stream of domain models.
     * Every time a row changes in the database, a new list is emitted.
     */
    fun observeAllMovies(): Flow<List<Movie>> =
        dao.getAllMovies().map { entities -> entities.map { it.toDomain() } }

    /**
     * READ: returns a single movie by id as a reactive stream.
     * Emits null if the movie does not exist (or was deleted).
     *
     * @param id the movie id as a string (navigation passes String arguments)
     */
    fun observeMovieById(id: String): Flow<Movie?> =
        dao.getMovieById(id.toLong()).map { it?.toDomain() }

    /**
     * CREATE: saves a new movie into the database.
     * @return the new movie's id (generated by the database)
     */
    suspend fun addMovie(name: String, description: String): Long {
        val entity = MovieEntity(
            name = name.trim(),
            description = description.trim(),
        )
        return dao.insert(entity)
    }

    /**
     * UPDATE: saves the changed movie back into the database.
     * The entity's id must already exist in the table.
     */
    suspend fun updateMovie(movie: Movie) {
        dao.update(MovieEntity.fromDomain(movie))
    }

    /**
     * DELETE: removes a movie from the database by its id.
     */
    suspend fun deleteMovie(id: String) {
        dao.deleteById(id.toLong())
    }
}
